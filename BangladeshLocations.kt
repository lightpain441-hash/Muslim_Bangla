data class UpazilaLocation(
    val id: String,
    val nameBangla: String,
    val districtBangla: String,
    val divisionBangla: String,
    val lat: Double,
    val lng: Double
) {
    val displayLabel: String
        get() = "$nameBangla, $districtBangla"
}

data class DistrictLocations(
    val id: String,
    val nameBangla: String,
    val divisionBangla: String,
    val lat: Double,
    val lng: Double,
    val upazilas: List<UpazilaLocation>
)

data class DivisionLocations(
    val id: String,
