    val allUpazilas: List<UpazilaLocation> by lazy {
        divisions.flatMap { div -> div.districts.flatMap { dist -> dist.upazilas } }
    }

    fun searchUpazilas(query: String): List<UpazilaLocation> {
        val clean = query.trim()
        if (clean.isEmpty()) return emptyList()
        return allUpazilas.filter {
            it.nameBangla.contains(clean) ||
                it.districtBangla.contains(clean) ||
                it.divisionBangla.contains(clean)
        }.take(25)
    }

    fun findNearestUpazila(lat: Double, lng: Double): UpazilaLocation? {
        if (lat !in 20.3..26.7 || lng !in 88.0..92.8) return null
        return allUpazilas.minByOrNull { u ->
            abs(u.lat - lat) + abs(u.lng - lng)
        }
    }

    fun resolveSelectionFromCityName(cityName: String): Triple<DivisionLocations, DistrictLocations, UpazilaLocation> {
        val matched = allUpazilas.firstOrNull {
            cityName.contains(it.nameBangla) && cityName.contains(it.districtBangla)
        } ?: allUpazilas.firstOrNull {
            cityName.contains(it.districtBangla)
        } ?: divisions.first().districts.first().upazilas.first()

        val div = divisions.first { d -> d.nameBangla == matched.divisionBangla }
        val dist = div.districts.first { d -> d.nameBangla == matched.districtBangla }
        return Triple(div, dist, matched)
    }
